<template>
  <view
    class="icon"
    :class="$attrs.class"
    :style="[iconStyle, $attrs.style]"
    :hover-class="hoverClass"
    @tap="onTap"
  >
    <svg class="icon-svg" viewBox="0 0 24 24" preserveAspectRatio="xMidYMid meet"><path fill="currentColor" d="M2 12c0 5.523 4.477 10 10 10s10-4.477 10-10c0-5.186-3.948-9.45-9.001-9.95-.55-.055-1 .398-1 .95 0 .553.45.994.999 1.062A8.001 8.001 0 0 1 12 20 8 8 0 0 1 7.5 5.385V7a1 1 0 1 0 2 0V3a1 1 0 0 0-1-1h-4a1 1 0 1 0 0 2H6a9.99 9.99 0 0 0-4 8"/></svg>
  </view>
</template>

<script setup lang="ts">
import { computed } from 'vue'

const props = defineProps({
  size: { type: [String, Number], default: 22 },
  color: { type: String, default: '' },
  hoverClass: { type: String, default: '' }
})

const iconSize = computed(() => {
  const size = props.size
  if (typeof size === 'number') return size + 'px'
  return size.endsWith('px') ? size : size + 'px'
})

const iconColor = computed(() => props.color || 'currentColor')

const iconStyle = computed(() => ({
  '--icon-size': iconSize.value,
  '--icon-color': iconColor.value
}))

const emit = defineEmits(['click'])
function onTap() {
  emit('click')
}
</script>

