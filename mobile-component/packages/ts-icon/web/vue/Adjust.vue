<template>
  <view
    class="icon"
    :class="$attrs.class"
    :style="[iconStyle, $attrs.style]"
    :hover-class="hoverClass"
    @tap="onTap"
  >
    <svg class="icon-svg" viewBox="0 0 24 24" preserveAspectRatio="xMidYMid meet"><path fill="currentColor" d="M19 3a2 2 0 0 1 2 2v14a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2zM5 19h14V5H5zm10-7a3 3 0 1 1-2.78 4.128 1 1 0 0 1-.22.022H7.5a1.15 1.15 0 0 1 0-2.3H12q.114 0 .22.021A3 3 0 0 1 15 12m0 2a1 1 0 1 0 0 2 1 1 0 0 0 0-2M9 6a3 3 0 0 1 2.771 1.85H16.5a1.15 1.15 0 0 1 0 2.3h-4.728A3 3 0 1 1 9 6m0 2a1 1 0 1 0 0 2 1 1 0 0 0 0-2"/></svg>
  </view>
</template>

<script setup lang="ts">
import { computed } from 'vue'

const props = defineProps({
  size: { type: [String, Number], default: 22 },
  color: { type: String, default: '' },
  hoverClass: { type: String, default: '' }
})

const iconSize = computed(() => {
  const size = props.size
  if (typeof size === 'number') return size + 'px'
  return size.endsWith('px') ? size : size + 'px'
})

const iconColor = computed(() => props.color || 'currentColor')

const iconStyle = computed(() => ({
  '--icon-size': iconSize.value,
  '--icon-color': iconColor.value
}))

const emit = defineEmits(['click'])
function onTap() {
  emit('click')
}
</script>

