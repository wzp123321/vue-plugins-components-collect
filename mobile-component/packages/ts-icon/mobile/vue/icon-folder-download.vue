    <!-- #ifdef H5 -->
    <svg class="icon-svg" viewBox="0 0 24 24" preserveAspectRatio="xMidYMid meet"><path fill="currentColor" d="M9.52 3a2 2 0 0 1 1.561.75l1.4 1.75H20a2 2 0 0 1 2 2V19a2 2 0 0 1-2 2H4a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2zm0 2H4v14h16V7.5h-7.52a2 2 0 0 1-1.561-.75zM12 10a1 1 0 0 1 1 1v2.709l.414-.415a1 1 0 0 1 1.414 1.415l-2.12 2.12a1 1 0 0 1-1.415 0l-2.121-2.12a1 1 0 1 1 1.414-1.415l.414.415V11a1 1 0 0 1 1-1"/></svg>
