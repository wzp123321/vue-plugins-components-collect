    <!-- #ifdef H5 -->
    <svg class="icon-svg" viewBox="0 0 24 24" preserveAspectRatio="xMidYMid meet"><path fill="currentColor" d="M11.178 15.957a1.01 1.01 0 0 1 1.563-.1l.08.1 2.981 4.168a1.01 1.01 0 0 1-.712 1.592l-.11.006H9.02a1.01 1.01 0 0 1-.881-1.505l.059-.093zm.822 2.29-1.056 1.476h2.112zM20 4a2 2 0 0 1 1.995 1.85L22 6v11a2 2 0 0 1-1.85 1.995L20 19h-4v-2h4V6H4v11h4v2H4a2 2 0 0 1-1.995-1.85L2 17V6a2 2 0 0 1 1.85-1.995L4 4z"/></svg>
