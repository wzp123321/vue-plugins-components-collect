<template>
  <view
    class="icon"
    :class="$attrs.class"
    :style="[iconStyle, $attrs.style]"
    :hover-class="hoverClass"
    @tap="onTap"
  >
    <!-- #ifdef H5 -->
    <svg class="icon-svg" viewBox="0 0 24 24" preserveAspectRatio="xMidYMid meet"><path fill="currentColor" d="M13.614 4a3 3 0 0 1 2.809 1.947l2.294 6.117a4.001 4.001 0 1 1-2.072.171L16.182 11 9.21 13.614a4 4 0 1 1-3.41-1.61L6.022 12 4.91 10H4a1 1 0 0 1 0-2h4a1 1 0 0 1 0 2h-.8l1.026 1.847 7.254-2.72-.93-2.478A1 1 0 0 0 13.614 6H11a1 1 0 0 1 0-2zm4.553 10.007L17.98 14a2 2 0 1 0 .186.007M6 14a2 2 0 1 0 0 4 2 2 0 0 0 0-4"/></svg>
    <!-- #endif -->
    <!-- #ifndef H5 -->
    <image :src="imgSrc" class="icon-image" />
    <!-- #endif -->
  </view>
</template>

<script setup lang="ts">
import { computed } from 'vue'
<!-- #ifndef H5 -->
import imgSrc from '@/uni_modules/@zpackage/mobile-package/ts-icon/mobile/uvue/icon-bicyle/bicyle.png'
<!-- #endif -->

const props = defineProps({
  size: { type: [String, Number], default: 22 },
  color: { type: String, default: '' },
  hoverClass: { type: String, default: '' }
})

const iconSize = computed(() => {
  const size = props.size
  if (typeof size === 'number') return size + 'px'
  return size.endsWith('px') ? size : size + 'px'
})

const iconColor = computed(() => props.color || 'currentColor')

const iconStyle = computed(() => ({
  '--icon-size': iconSize.value,
  '--icon-color': iconColor.value
}))

const emit = defineEmits(['click'])
function onTap() {
  emit('click')
}
</script>

